#!/usr/bin/env python3
"""Builds docs/workflow.html (standalone page) from docs/workflow.fragment.html.

The fragment is the source published as a claude.ai Artifact (no <html>/<head>/<body>,
Mermaid rendered by the host). The standalone page wraps it in a full HTML document and
loads Mermaid from a CDN so it opens in any browser or on GitHub Pages.
"""

from __future__ import annotations

from pathlib import Path

DOCS = Path(__file__).resolve().parents[1] / "docs"
MERMAID = "https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.min.js"


def main() -> None:
    src = (DOCS / "workflow.fragment.html").read_text(encoding="utf-8")
    # Head = everything up to the end of the first <style> block; body = the rest.
    cut = src.index("</style>") + len("</style>")
    head, body = src[:cut], src[cut:]
    page = f"""<!doctype html>
<html lang="es" data-lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<!-- Generated by tools/build_workflow_page.py from docs/workflow.fragment.html. Do not edit. -->
{head}
</head>
<body>{body}
<script src="{MERMAID}"></script>
<script>
  // Render Mermaid with a theme that matches the viewer's light/dark preference
  mermaid.initialize({{
    startOnLoad: true,
    theme: matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "default",
  }});
</script>
</body>
</html>
"""
    (DOCS / "workflow.html").write_text(page, encoding="utf-8")
    print("wrote docs/workflow.html")


if __name__ == "__main__":
    main()
